import test from 'node:test';
import assert from 'node:assert/strict';
import { access, readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

async function loadPortfolio() {
  const dataUrl = pathToFileURL(path.join(root, 'src/data/portfolio.js')).href;
  return (await import(`${dataUrl}?test=${Date.now()}`)).portfolio;
}
const readText = (relativePath) => readFile(path.join(root, relativePath), 'utf8');

async function collectTextFiles(relativePath) {
  const entries = await readdir(path.join(root, relativePath), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const item = path.join(relativePath, entry.name);
    if (entry.isDirectory()) files.push(...await collectTextFiles(item));
    else if (/\.(?:astro|html|js|mjs|css|xml|txt|md)$/.test(entry.name)) files.push(item);
  }
  return files;
}

test('portfolio data uses the approved truthful positioning and employment dates', async () => {
  const portfolio = await loadPortfolio();
  assert.equal(portfolio.positioning, 'AdTech Solutions Engineer · Technical Solutions Consultant');
  assert.equal(portfolio.experience[0].title, 'AdTech Solutions Engineer (Technical Solutions Consultant)');
  assert.equal(portfolio.experience[0].dates, '04/2025 — 07/2026');
  assert.equal(portfolio.experience[1].title, 'Cloud Solution Architect');
  assert.equal(portfolio.experience[1].dates, '08/2022 — 03/2025');
});

test('portfolio data exposes recruiter and shipped-project links', async () => {
  const portfolio = await loadPortfolio();
  const project = portfolio.projects.find((item) => item.slug === 'knowledge-nebula');
  assert.equal(portfolio.resumeUrl, '/Chris-Johnson-Resume.pdf');
  assert.equal(portfolio.contact.emailUrl, 'mailto:Chrismjohnson19@gmail.com');
  assert.equal(portfolio.contact.linkedinUrl, 'https://linkedin.com/in/christopherjohnson98');
  assert.equal(project.caseStudyUrl, '/work/knowledge-nebula/');
  assert.equal(project.liveUrl, 'https://document-graph-explorer.vercel.app');
  assert.equal(project.repoUrl, 'https://github.com/chrisatom1998/document-graph-explorer');
});

test('public web source excludes stale employment language, unsupported claims, and phone links', async () => {
  const files = [];
  for (const scanRoot of ['src', 'public', 'scripts', 'work']) files.push(...await collectTextFiles(scanRoot));
  files.push('index.html', 'styles.css', 'site.js', 'robots.txt', 'sitemap.xml');
  const banned = ['tel:', '678-642-6551', 'Solutions Architect · Google', '04/2025 — present', '04/2025 - Present', 'platform adoption twofold', 'upward of 35%', '45 publisher-oriented solutions'];
  for (const relativePath of files) {
    const contents = await readText(relativePath);
    for (const phrase of banned) assert.equal(contents.includes(phrase), false, `${relativePath} contains banned phrase: ${phrase}`);
  }
});

