  const home = await readText('index.html');
  const expectedLinks = ['/Chris-Johnson-Resume.pdf', 'mailto:Chrismjohnson19@gmail.com', 'https://linkedin.com/in/christopherjohnson98', '/work/knowledge-nebula/', 'https://document-graph-explorer.vercel.app', 'https://github.com/chrisatom1998/document-graph-explorer'];
